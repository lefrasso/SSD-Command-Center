  'in-delivery': [COLORS.warning, 'clock', 'In delivery'], complete: [COLORS.positive, 'check', 'Complete'],
  investigating: [COLORS.warning, 'clock', 'Investigating'], mitigating: [COLORS.info, 'clock', 'Mitigating'],
  resolved: [COLORS.positive, 'check', 'Resolved'], open: [COLORS.negative, 'warning', 'Open'],
  'in-progress': [COLORS.warning, 'clock', 'In progress'], done: [COLORS.positive, 'check', 'Done'],
  sourcing: [COLORS.neutral, 'clock', 'Sourcing'], selection: [COLORS.neutral, 'clock', 'Selection'],
  onboarding: [COLORS.info, 'clock', 'Onboarding'], active: [COLORS.positive, 'check', 'Active'],
  offboarding: [COLORS.warning, 'clock', 'Offboarding'], exiting: [COLORS.warning, 'clock', 'Exiting'],
  draft: [COLORS.neutral, 'clock', 'Draft'], closed: [COLORS.neutral, 'check', 'Closed'],
