// ---- Meter (progress bar) ----
export function meter(pct, color) {
  return `<div class="meter"><div class="meter-fill" style="width:${Math.max(0, Math.min(100, pct))}%;background:${color || COLORS.brand}"></div></div>`;
}

// ---- Shared body-level drawer ----
export function openDrawer(title, bodyHtml, wire) {
  let scrim = document.getElementById('g-scrim');
  let dr = document.getElementById('g-drawer');
  if (!scrim) { scrim = document.createElement('div'); scrim.id = 'g-scrim'; scrim.className = 'drawer-scrim'; document.body.appendChild(scrim); scrim.addEventListener('click', closeDrawer); }
  if (!dr) { dr = document.createElement('aside'); dr.id = 'g-drawer'; dr.className = 'drawer'; document.body.appendChild(dr); }
  dr.innerHTML = `<div class="drawer-head"><span class="drawer-title">${title}</span><button class="icon-btn" id="g-drawer-close" aria-label="Close" style="color:var(--fg-2)">${icon('x', 20)}</button></div><div class="drawer-body">${bodyHtml}</div>`;
  scrim.classList.add('open'); dr.classList.add('open');
  dr.querySelector('#g-drawer-close').addEventListener('click', closeDrawer);
  if (wire) wire(dr);
}
export function closeDrawer() {
  const s = document.getElementById('g-scrim'); const d = document.getElementById('g-drawer');
  if (s) s.classList.remove('open'); if (d) d.classList.remove('open');
}
