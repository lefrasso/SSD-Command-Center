export function statusPill(status) {
  const [c, ic, label] = STATUS[status] || [COLORS.neutral, 'clock', status];
  return `<span class="pill" style="color:${c}">${icon(ic, 14)}<span class="pill-label">${esc(label)}</span></span>`;
}
