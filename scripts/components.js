// Shared UI render helpers (return HTML strings) + Chart.js wrappers.
import { icon } from './icons.js';

export const COLORS = {
  positive: '#0e700e', neutral: '#616161', negative: '#c4314b', warning: '#bc4b09', info: '#0f6cbd',
  sev1: '#a80000', sev2: '#c4314b', sev3: '#bc4b09', sev4: '#616161', brand: '#0f6cbd',
};
export const CHART_PALETTE = ['#0f6cbd', '#2aa0a4', '#6b69d6', '#f7a600', '#c4314b', '#5c2e91', '#0e700e'];

export function esc(v) {
  return String(v == null ? '' : v).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}
export const scoreColor = (s) => (s >= 4.4 ? COLORS.positive : s >= 3.8 ? COLORS.warning : COLORS.negative);
export const utilColor = (p) => (p >= 80 && p <= 92 ? COLORS.positive : p > 92 ? COLORS.negative : p >= 65 ? COLORS.warning : COLORS.neutral);

export function aiChip(label = 'AI-generated') {
  return `<span class="ai-chip" role="note" title="Simulated AI output. Advisory only — a human decides. In production, generated by Azure OpenAI over SSD IQ.">${icon('sparkle', 14)}${esc(label)}</span>`;
}

